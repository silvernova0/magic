#!/usr/bin/env python3
"""
Discover popular deck tags from Archidekt by sampling high-view decks
This helps us build a comprehensive themes list for targeted scraping
"""
import requests
import json
from collections import Counter

def discover_archidekt_tags(num_decks=200):
    """Sample popular decks to discover common tags"""
    api_base = 'https://archidekt.com/api'
    session = requests.Session()
    session.headers.update({
        'User-Agent': 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36',
        'Accept': 'application/json'
    })
    
    tag_counter = Counter()
    bracket_counter = Counter()
    decks_checked = 0
    
    print("Discovering Archidekt deck tags...")
    print(f"Sampling {num_decks} high-view Commander decks\n")
    
    # Search for Commander decks
    page = 1
    while decks_checked < num_decks and page <= 5:
        try:
            url = f'{api_base}/decks/v3/'
            params = {
                'formats': 7,  # Commander
                'orderBy': '-viewCount',
                'page': page,
                'pageSize': 100
            }
            
            response = session.get(url, params=params, timeout=15)
            response.raise_for_status()
            data = response.json()
            
            results = data.get('results', [])
            if not results:
                break
            
            # Fetch details for each deck to get tags
            for deck_summary in results:
                if decks_checked >= num_decks:
                    break
                
                deck_id = deck_summary.get('id')
                
                try:
                    deck_url = f'{api_base}/decks/{deck_id}/'
                    deck_response = session.get(deck_url, timeout=15)
                    deck_response.raise_for_status()
                    deck_data = deck_response.json()
                    
                    # Extract tags
                    deck_tags = deck_data.get('deckTags', [])
                    for tag_obj in deck_tags:
                        tag_name = tag_obj.get('name')
                        if tag_name:
                            tag_counter[tag_name] += 1
                    
                    # Extract bracket
                    bracket = deck_data.get('edhBracket')
                    if bracket:
                        bracket_counter[bracket] += 1
                    
                    decks_checked += 1
                    
                    if decks_checked % 20 == 0:
                        print(f"Checked {decks_checked} decks...")
                    
                except Exception as e:
                    print(f"Error fetching deck {deck_id}: {e}")
                    continue
            
            page += 1
            
        except Exception as e:
            print(f"Error on page {page}: {e}")
            break
    
    print(f"\n✓ Analyzed {decks_checked} decks\n")
    
    # Report findings
    print("="*60)
    print("TOP 50 MOST COMMON TAGS")
    print("="*60)
    for tag, count in tag_counter.most_common(50):
        percentage = (count / decks_checked) * 100
        print(f"{tag:30s} {count:4d} decks ({percentage:5.1f}%)")
    
    print(f"\n{'='*60}")
    print("EDH BRACKET DISTRIBUTION")
    print("="*60)
    for bracket in sorted(bracket_counter.keys()):
        count = bracket_counter[bracket]
        percentage = (count / decks_checked) * 100
        bracket_names = {
            1: "Precon Level",
            2: "Casual Optimized",
            3: "Focused/Tuned",
            4: "High Power",
            5: "cEDH"
        }
        bracket_name = bracket_names.get(bracket, f"Bracket {bracket}")
        print(f"Bracket {bracket} ({bracket_name:20s}): {count:4d} decks ({percentage:5.1f}%)")
    
    # Save results
    output = {
        'tags': [{'tag': tag, 'count': count} for tag, count in tag_counter.most_common()],
        'brackets': dict(bracket_counter),
        'total_decks': decks_checked
    }
    
    output_file = 'data/archidekt_tag_analysis.json'
    with open(output_file, 'w') as f:
        json.dump(output, f, indent=2)
    
    print(f"\n💾 Results saved to {output_file}")
    
    # Generate updated themes file
    print(f"\n{'='*60}")
    print("GENERATING UPDATED THEMES FILE")
    print("="*60)
    
    with open('data/archidekt_themes_discovered.txt', 'w') as f:
        f.write("# Archidekt Deck Tags (Discovered from Top Decks)\n")
        f.write(f"# Generated by analyzing {decks_checked} high-view Commander decks\n")
        f.write("# Ordered by popularity (most common first)\n\n")
        
        f.write("# Top 50 Most Common Tags\n")
        for tag, count in tag_counter.most_common(50):
            percentage = (count / decks_checked) * 100
            f.write(f"{tag}  # {count} decks ({percentage:.1f}%)\n")
    
    print(f"✓ Updated themes file: data/archidekt_themes_discovered.txt")

if __name__ == '__main__':
    discover_archidekt_tags(num_decks=200)
